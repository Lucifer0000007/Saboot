# Import a recorded voice line (any format ffmpeg reads) as a Saboot clip: mono Opus in WebM, <= 20 KB.
#   npm run audio:import -- -In C:\rec\alert-hi.m4a -Clip alert-relief -Lang hi -Ffmpeg C:\path\ffmpeg.exe
# Then regenerates src/lib/clips.ts from the files in public/audio. See docs/recording-script.md.
param(
  [Parameter(Mandatory = $true)][string]$In,
  [Parameter(Mandatory = $true)][ValidateSet('alert-relief', 'reg-relief', 'alert-pmfby', 'reg-pmfby')][string]$Clip,
  [Parameter(Mandatory = $true)][ValidateSet('en', 'hi', 'pa')][string]$Lang,
  [Parameter(Mandatory = $true)][string]$Ffmpeg
)
$ErrorActionPreference = 'Stop'
$audio = Join-Path $PSScriptRoot '..\public\audio'
New-Item -ItemType Directory -Force $audio | Out-Null
$out = Join-Path $audio "$Clip-$Lang.webm"
foreach ($kbps in 16, 12, 10) {
  & $Ffmpeg -hide_banner -loglevel error -y -i $In -ac 1 -ar 16000 -af 'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse' -c:a libopus -b:a "${kbps}k" -application voip $out
  $size = (Get-Item $out).Length
  if ($size -le 20480) { break }
}
if ($size -gt 20480) { throw "$out is $size bytes, over the 20 KB budget even at 10 kbps: record a shorter line." }
Write-Host "$Clip-$Lang.webm $size bytes at ${kbps} kbps"

# regenerate the clip manifest the app reads
$map = @{}
Get-ChildItem $audio -Filter '*.webm' | ForEach-Object {
  if ($_.BaseName -match '^([\w-]+)-(en|hi|pa)$') {
    if (-not $map.ContainsKey($Matches[1])) { $map[$Matches[1]] = @() }
    $map[$Matches[1]] += $Matches[2]
  }
}
$entries = ($map.Keys | Sort-Object | ForEach-Object { "$_`: [" + (($map[$_] | Sort-Object | ForEach-Object { "'$_'" }) -join ', ') + ']' }) -join ', '
$ts = "// Generated by scripts/audio-import.ps1 from public/audio — which voice clips exist per language.`nimport type { Lang } from '../sim/types';`n`nexport const CLIPS: Record<string, Lang[]> = { $entries };`n"
Set-Content -Path (Join-Path $PSScriptRoot '..\src\lib\clips.ts') -Value $ts -Encoding utf8 -NoNewline
Write-Host 'updated src/lib/clips.ts'
