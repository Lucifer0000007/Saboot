// i18n gate: every English key exists in hi.ts and pa.ts (and nothing extra), and every Hindi/Punjabi
// entry carries a review flag (`// needs-native-review` or `// reviewed`). `--write` regenerates
// docs/translation-review.md (the list the README links to). Unused keys are reported as warnings.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const write = process.argv.includes('--write');
const read = (l) => readFileSync(`src/i18n/${l}.ts`, 'utf8');
const KEY = /^\s*'?([\w.]+)'?\s*:\s*(.*)$/;

/** Parse a locale file into { key, value(first line), flag, line } entries (top-level keys only). */
function entries(l) {
  const out = [];
  const lines = read(l).split(/\r?\n/);
  let depth = 0;
  lines.forEach((line, i) => {
    const m = depth === 0 ? line.match(KEY) : null;
    if (m && !line.trim().startsWith('//') && i > 0 && !/^const |^export /.test(line.trim())) {
      const flag = /\/\/\s*needs-native-review/.test(line) ? 'needs-native-review' : /\/\/\s*reviewed/.test(line) ? 'reviewed' : null;
      let value = m[2].replace(/\s*\/\/.*$/, '').replace(/,\s*$/, '');
      if (value.trim() === '[') {
        const parts = [];
        for (let j = i + 1; j < lines.length && !/^\s*\],?/.test(lines[j]); j++) parts.push(lines[j].trim().replace(/,$/, ''));
        value = parts.join(' ');
      }
      out.push({ key: m[1], value: value.replace(/^'|'$/g, ''), flag, line: i + 1 });
    }
    depth += (line.match(/\[/g) || []).length - (line.match(/\]/g) || []).length;
    if (line.includes('{') && i === 0) depth = 0;
  });
  return out;
}

let fail = 0;
const en = entries('en');
const enKeys = new Set(en.map((e) => e.key));
const dup = en.filter((e, i) => en.findIndex((x) => x.key === e.key) !== i);
if (dup.length) { console.log('  ✗ en: duplicate keys ' + dup.map((d) => d.key).join(', ')); fail = 1; }
const loc = {};
for (const l of ['hi', 'pa']) {
  const es = entries(l);
  loc[l] = Object.fromEntries(es.map((e) => [e.key, e]));
  const keys = new Set(es.map((e) => e.key));
  const miss = [...enKeys].filter((k) => !keys.has(k));
  const extra = [...keys].filter((k) => !enKeys.has(k));
  const unflagged = es.filter((e) => !e.flag);
  const pending = es.filter((e) => e.flag === 'needs-native-review').length;
  const ok = !miss.length && !extra.length && !unflagged.length;
  if (!ok) fail = 1;
  console.log(`  ${ok ? '✓' : '✗'} ${l}: ${keys.size} keys, ${pending} need native review` +
    (miss.length ? ` · missing ${miss.join(', ')}` : '') + (extra.length ? ` · extra ${extra.join(', ')}` : '') +
    (unflagged.length ? ` · no review flag on lines ${unflagged.map((e) => e.line).join(', ')}` : ''));
}

// unused keys (warning only): look for the literal key or its dynamic prefix in src/
const walk = (d) => readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]));
// the dictionaries themselves are not usage; src/lib/i18n.ts (which shows a toast) is
const code = walk('src').filter((f) => /\.tsx?$/.test(f) && !f.split(/[\\/]/).includes('i18n')).map((f) => readFileSync(f, 'utf8')).join('\n');
// 'boot.' keys are read by scripts/postbuild.mjs (the inline boot script's messages), not by src/
const dynamic = ['boot.', 'shot.', 'crop.', 'm.', 'net.', 'conn.', 'sync.st.', 'set.t', 'faq.', 'pb.', 'tour.s', 'arch.', 'wf.', 'rs.', 'sim.tab.', 'conn.live.', 'f.nav.', 'as.', 'st.', 'fl.s', 'rail.', 'cad.', 'lang.name.'];
// a rail variant (key.pmfby or key.relief) is used when its base key is: the app reads them with trr()
const baseOf = (k) => k.replace(/\.(pmfby|relief)$/, '');
const unused = en.filter((e) => { const k = baseOf(e.key); return !code.includes(`'${k}'`) && !code.includes(`"${k}"`) && !dynamic.some((p) => k.startsWith(p)) && !['days', 'months', 'u.d', 'u.h', 'u.m', 'u.day', 'u.days', 'u.min'].includes(k); });
if (unused.length) console.log(`  ⚠ ${unused.length} key(s) look unused: ${unused.map((e) => e.key).join(', ')}`);

if (write) {
  mkdirSync('docs', { recursive: true });
  const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
  const rows = en.map((e) => `| \`${e.key}\` | ${esc(e.value)} | ${esc(loc.hi[e.key]?.value)} | ${esc(loc.pa[e.key]?.value)} | ${loc.hi[e.key]?.flag === 'reviewed' ? 'reviewed' : 'needs review'} / ${loc.pa[e.key]?.flag === 'reviewed' ? 'reviewed' : 'needs review'} |`);
  writeFileSync('docs/translation-review.md', [
    '# Translation review list',
    '',
    'Generated by `npm run i18n`. Every Hindi and Punjabi string in Saboot was machine-drafted and is **not verified**.',
    'A native speaker should check each row; when a line is checked, change its `// needs-native-review` flag in',
    '`src/i18n/hi.ts` or `src/i18n/pa.ts` to `// reviewed` and re-run `npm run i18n`. The brand name Saboot is written',
    'सबूत / ਸਬੂਤ ("proof") in the Indic strings; long-form answers are flattened to one cell here.',
    '',
    '| Key | English | Hindi | Punjabi | Status (hi / pa) |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n'));
  console.log(`  wrote docs/translation-review.md (${rows.length} rows)`);
}
process.exit(fail);
